#!/usr/bin/env node
/**
 * Print (or write) coverage statistics for the NaijaBase datasets.
 *
 * Usage:
 *   node scripts/stats.mjs            # print markdown to stdout
 *   node scripts/stats.mjs --write    # write docs/STATS.md
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const write = process.argv.includes("--write");

const load = (rel) => JSON.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));

const states = load("data/base/states.json");
const lgas = load("data/base/lgas.json");
const wards = load("data/location/wards.json");
const wardsByLga = load("data/location/wards-by-lga.json");
const languages = load("data/base/state-languages.json");
const festivals = load("data/base/festivals.json");
const parties = load("data/politics/parties.json");
const senatorial = load("data/politics/constituencies/senatorial-districts.json");
const federal = load("data/politics/constituencies/federal-constituencies.json");

const byState = (items, nameKey) => {
  const map = new Map();
  for (const item of items) {
    const key = item[nameKey];
    map.set(key, (map.get(key) ?? 0) + 1);
  }
  return map;
};

const lgaByState = byState(lgas, "stateName");
const wardByState = byState(wards, "stateName");
const langByState = new Map(
  Object.entries(languages).map(([id, list]) => [id, list.length]),
);
const festivalsByState = byState(festivals, "stateName");

const total = (map) => [...map.values()].reduce((a, b) => a + b, 0);
const totalPollingUnits = states.reduce(
  (sum, s) => sum + (s.pollingUnitCount ?? 0),
  0,
);
const totalWardsIndex = Object.values(wardsByLga).reduce(
  (sum, list) => sum + list.length,
  0,
);

const fmt = (n) => n.toLocaleString("en-US");

const lines = [];
lines.push("# Dataset statistics");
lines.push("");
lines.push(
  "> Generated by `npm run stats:write`. Do not edit by hand.",
);
lines.push("");
lines.push("## Totals");
lines.push("");
lines.push("| Metric | Count |");
lines.push("|--------|------:|");
lines.push(`| States + FCT | ${fmt(states.length)} |`);
lines.push(`| Local Government Areas | ${fmt(lgas.length)} |`);
lines.push(`| Wards | ${fmt(wards.length)} |`);
lines.push(`| Ward-to-LGA index entries | ${fmt(totalWardsIndex)} |`);
lines.push(`| Polling units (aggregate count) | ${fmt(totalPollingUnits)} |`);
lines.push(`| Geopolitical zones | 6 |`);
lines.push(`| States with language lists | ${fmt(langByState.size)} |`);
lines.push(`| Festivals | ${fmt(festivals.length)} |`);
lines.push(`| Political parties | ${fmt(Object.keys(parties.parties).length)} |`);
lines.push(`| Senatorial districts | ${fmt(senatorial.length)} |`);
lines.push(`| Federal constituencies | ${fmt(federal.length)} |`);
lines.push("");
lines.push("## By state");
lines.push("");
lines.push(
  "| State | Region | LGAs | Wards | Polling units | Languages | Festivals |",
);
lines.push("|-------|--------|-----:|------:|--------------:|----------:|----------:|");
for (const s of states) {
  const lga = lgaByState.get(s.name) ?? 0;
  const ward = wardByState.get(s.name) ?? 0;
  const langs = langByState.get(s.id) ?? 0;
  const fests = festivalsByState.get(s.name) ?? 0;
  lines.push(
    `| ${s.name} | ${s.region} | ${lga} | ${ward} | ` +
      `${fmt(s.pollingUnitCount ?? 0)} | ${langs} | ${fests} |`,
  );
}
lines.push("");
lines.push(
  `**Totals:** ${states.length} states/FCT, ${lgas.length} LGAs, ` +
    `${fmt(wards.length)} wards, ${fmt(totalPollingUnits)} polling units.`,
);
lines.push("");

const output = lines.join("\n");

if (write) {
  const target = path.join(ROOT, "docs/STATS.md");
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output);
  console.log(`Wrote ${path.relative(ROOT, target)}`);
} else {
  process.stdout.write(output);
}
